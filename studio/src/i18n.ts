export const DICTIONARIES: Record<Locale, Dictionary> = { en: EN, tr: TR, zh: ZH, de: DE, ru: RU, es: ES };

export function detectInitialLocale(): Locale {
  try {
    const saved = window.localStorage.getItem("omrkit_locale") as Locale | null;
    if (saved && saved in DICTIONARIES) return saved;
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase() as Locale;
    if (nav in DICTIONARIES) return nav;
  } catch {
    // ignore storage restriction
  }
  return "en";
}
