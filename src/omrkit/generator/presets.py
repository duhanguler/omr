def get_sheet_preset(preset_id: str) -> SheetSpec:
    """Look up a single preset by ID."""
    presets = get_sheet_presets()
    if preset_id not in presets:
        available = ", ".join(sorted(presets))
        raise ValueError(f"Unknown sheet preset '{preset_id}'. Available: {available}")
    return presets[preset_id]
